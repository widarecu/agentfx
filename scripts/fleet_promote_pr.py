#!/usr/bin/env python3
"""Open or refresh the promote PR `feat/agent-fleet` -> `main` (AFX-69).

Run by `.github/workflows/agent-fleet-promote.yml`. Each run:

1. Exits unless `feat/agent-fleet` has content `main` lacks: merging it into
   `main` would leave `main`'s tree unchanged. Not ancestry or a plain tip
   diff: back-merge commits make the fleet branch look ahead with nothing to
   promote, and a hotfix on `main` that hasn't been back-merged yet makes the
   tips differ (CLAUDE.md -> Branch flow).
2. Lists every PR merged into `feat/agent-fleet` that is not on `main` yet
   (first-parent `git log main..feat/agent-fleet`, back-merge PRs skipped),
   with risk and touched files. Money-path PRs go first.
3. Opens the promote PR (head `feat/agent-fleet`, labels `promote` +
   `needs-wilson`) or re-renders the body of the open one. A hand-cut
   `promote/*` PR (a frozen promote) wins: the script closes its own PR
   and stands down until the frozen one is merged or closed. Only the block
   between the markers is rewritten; anything Wilson adds outside it stays.
   It never enables auto-merge.
4. Comments once per Linear issue (`AFX-<n>` in a listed PR title) with a
   link to the promote PR, when `LINEAR_API_KEY` is set.

Risk comes from the Linear issue's Risk label. Without `LINEAR_API_KEY`
(or when the lookup fails) a `needs-wilson` label on the merged PR counts
as Money-path.

Stdlib only, plus the `gh` CLI (authenticated through `GH_TOKEN`):

    python3 scripts/fleet_promote_pr.py --dry-run     # print, change nothing
    python3 scripts/fleet_promote_pr.py --no-create   # refresh an open PR only
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import urllib.request
from dataclasses import dataclass, field
from datetime import UTC, datetime

BASE = "main"
HEAD = "feat/agent-fleet"
PROMOTE_LABEL = "promote"
NEEDS_WILSON = "needs-wilson"
MONEY_PATH = "Money-path"
RISK_LABELS = (MONEY_PATH, "Normal")

START = "<!-- fleet-promote:start -->"
END = "<!-- fleet-promote:end -->"
# GitHub rejects PR bodies over 65,536 chars; leave room for Wilson's notes.
MAX_SECTION = 60_000
MAX_FILES = 8

LINEAR_URL = "https://api.linear.app/graphql"
_AFX_RE = re.compile(r"\bAFX-(\d+)\b", re.IGNORECASE)


@dataclass
class MergedPR:
    number: int
    title: str
    url: str
    labels: list[str] = field(default_factory=list)
    files: list[str] = field(default_factory=list)
    risk: str = "unknown"


@dataclass
class DirectCommit:
    sha: str
    subject: str


# ─────────────────────────────────────────────────────────────────────
# Pure helpers (unit-tested)
# ─────────────────────────────────────────────────────────────────────


def afx_ids(title: str) -> list[str]:
    """`AFX-<n>` tags in a PR title, upper-cased, first-seen order."""
    seen: list[str] = []
    for m in _AFX_RE.finditer(title):
        ident = f"AFX-{m.group(1)}"
        if ident not in seen:
            seen.append(ident)
    return seen


def pick_risk(linear_risks: list[str | None], pr_labels: list[str]) -> str:
    """Highest risk across the PR's Linear issues, else the GitHub fallback."""
    if MONEY_PATH in linear_risks:
        return MONEY_PATH
    if any(r for r in linear_risks):
        return next(r for r in linear_risks if r)
    if NEEDS_WILSON in pr_labels:
        return f"{MONEY_PATH} (inferred from `{NEEDS_WILSON}`)"
    return "unknown"


def is_money_path(risk: str) -> bool:
    return risk.startswith(MONEY_PATH)


def format_files(files: list[str], limit: int = MAX_FILES) -> str:
    if not files:
        return "(none)"
    shown = ", ".join(f"`{f}`" for f in files[:limit])
    extra = len(files) - limit
    return f"{shown} +{extra} more" if extra > 0 else shown


def render_line(pr: MergedPR) -> str:
    return (
        f"- #{pr.number} {pr.title} — risk: {pr.risk} — files: {format_files(pr.files)}"
    )


def render_section(
    prs: list[MergedPR],
    direct: list[DirectCommit],
    *,
    repo: str,
    head_sha: str,
    now: datetime,
    max_len: int = MAX_SECTION,
) -> str:
    """The auto-managed block of the promote PR body, markers included.

    `prs` is in merge order (oldest first); Money-path PRs move to the top.
    Lines are dropped from the end, with a visible note, if the block would
    exceed `max_len`.
    """
    money = [p for p in prs if is_money_path(p.risk)]
    rest = [p for p in prs if not is_money_path(p.risk)]
    compare = f"https://github.com/{repo}/compare/{BASE}...{HEAD}"

    head = [
        START,
        f"## Waiting on `{HEAD}`",
        "",
        "Auto-generated by `agent-fleet-promote.yml` (AFX-69) and refreshed "
        f"on every merge into `{HEAD}`. Text outside this block is kept.",
        "",
        '**Merge with "Create a merge commit". Never squash** '
        "(CLAUDE.md -> Branch flow).",
    ]
    body: list[str] = []
    if money:
        body += ["", f"### {MONEY_PATH} — review first", *map(render_line, money)]
    if rest:
        body += ["", "### Merged PRs", *map(render_line, rest)]
    if direct:
        body += ["", "### Direct commits (no PR)"]
        body += [f"- `{c.sha[:7]}` {c.subject}" for c in direct]
    if not prs and not direct:
        body += ["", "_No PRs found; see the diff._"]
    tail = [
        "",
        f"Full diff: {compare}",
        f"_Refreshed {now:%Y-%m-%d %H:%M} UTC from `{head_sha[:7]}`._",
        END,
    ]

    def size(lines: list[str]) -> int:
        return len("\n".join(lines))

    if size(head + body + tail) > max_len:
        dropped = 0
        note = ""
        while body and size(head + body + [note] + tail) > max_len:
            body.pop()
            dropped += 1
            note = f"\n… {dropped} more lines not shown. See the full diff."
        body.append(note)
    return "\n".join(head + body + tail)


def merge_body(existing: str | None, section: str) -> str:
    """Swap the marked block in `existing`, or append it if absent."""
    existing = existing or ""
    start, end = existing.find(START), existing.find(END)
    if start != -1 and end > start:
        return existing[:start] + section + existing[end + len(END) :]
    if not existing.strip():
        return section
    return existing.rstrip() + "\n\n" + section


def find_auto_promote(open_prs: list[dict]) -> dict | None:
    """The open PR headed by `feat/agent-fleet`, i.e. the one this script manages."""
    return next((pr for pr in open_prs if pr.get("headRefName") == HEAD), None)


def select_open_promote(open_prs: list[dict]) -> tuple[dict | None, str]:
    """Pick the open promote PR into `main`, if any.

    A hand-cut `promote/*` or `promote`-labelled PR (`"manual"`) wins over
    the `feat/agent-fleet`-headed one (`"auto"`): cutting `promote/*` is how
    Wilson freezes a promote, so it must take over from the live PR.
    Returns `(None, "")` when neither is open.
    """
    for pr in open_prs:
        if pr.get("headRefName") == HEAD:
            continue
        labels = {lbl.get("name") for lbl in pr.get("labels") or []}
        if pr.get("headRefName", "").startswith("promote/") or PROMOTE_LABEL in labels:
            return pr, "manual"
    auto = find_auto_promote(open_prs)
    return (auto, "auto") if auto else (None, "")


def promote_title(now: datetime) -> str:
    return f"Promote {HEAD} → {BASE}: {now:%Y-%m-%d}"


def linear_marker(promote_number: int) -> str:
    return f"<!-- afx-69:promote-pr:{promote_number} -->"


def linear_comment(pr: MergedPR, *, promote_url: str, promote_number: int) -> str:
    return (
        f"Merged to `{HEAD}` in #{pr.number} ({pr.url}). Not on `{BASE}` yet.\n\n"
        f"Promote PR: {promote_url}\n\n"
        f"{linear_marker(promote_number)}\n"
        "_Posted by agent-fleet-promote.yml (AFX-69)._"
    )


def pick_merged_pr(candidates: list[dict], sha: str) -> dict | None:
    """The PR that landed `sha` on `feat/agent-fleet`, if it should be listed.

    Back-merge PRs (head `main`) are skipped: their content is already on
    `main`.
    """
    for pr in candidates:
        if not pr.get("merged_at") or (pr.get("base") or {}).get("ref") != HEAD:
            continue
        if pr.get("merge_commit_sha") not in (None, sha):
            continue
        if (pr.get("head") or {}).get("ref") == BASE:
            return None
        return pr
    return None


