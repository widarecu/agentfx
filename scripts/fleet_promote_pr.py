def _run(*cmd: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, check=check, capture_output=True, text=True)


def _gh_json(*args: str):
    return json.loads(_run("gh", *args).stdout or "null")


def warn(msg: str) -> None:
    print(f"::warning ::{msg}")


def fleet_has_new_content() -> bool:
    """True when merging `feat/agent-fleet` into `main` would change `main`."""
    base, head = f"origin/{BASE}", f"origin/{HEAD}"
    if (
        _run("git", "merge-base", "--is-ancestor", head, base, check=False).returncode
        == 0
    ):
        return False
    res = _run("git", "merge-tree", "--write-tree", base, head, check=False)
    if res.returncode == 1:
        return True  # conflicts: the fleet branch carries changes main lacks
    if res.returncode == 0:
        merged = res.stdout.split()[0]
        return merged != _run("git", "rev-parse", f"{base}^{{tree}}").stdout.strip()
    warn(f"git merge-tree failed ({res.stderr.strip()}); falling back to a tip diff")
    return _run("git", "diff", "--quiet", base, head, check=False).returncode != 0


def unpromoted_commits() -> list[tuple[str, str]]:
    out = _run(
        "git",
        "log",
        "--first-parent",
        "--reverse",
        "--format=%H%x09%s",
        f"origin/{BASE}..origin/{HEAD}",
    ).stdout
    return [tuple(line.split("\t", 1)) for line in out.splitlines() if "\t" in line]


def collect(repo: str) -> tuple[list[MergedPR], list[DirectCommit]]:
    prs: list[MergedPR] = []
    direct: list[DirectCommit] = []
    seen: set[int] = set()
    for sha, subject in unpromoted_commits():
        candidates = _gh_json("api", f"repos/{repo}/commits/{sha}/pulls") or []
        pr = pick_merged_pr(candidates, sha)
        if pr is None:
            if not any((c.get("head") or {}).get("ref") == BASE for c in candidates):
                if not subject.startswith("Merge "):
                    direct.append(DirectCommit(sha, subject))
            continue
        if pr["number"] in seen:
            continue
        seen.add(pr["number"])
        files = _run(
            "gh",
            "api",
            "--paginate",
            f"repos/{repo}/pulls/{pr['number']}/files",
            "--jq",
            ".[].filename",
        ).stdout.split()
        prs.append(
            MergedPR(
                number=pr["number"],
                title=pr["title"],
                url=pr["html_url"],
                labels=[lbl["name"] for lbl in pr.get("labels") or []],
                files=files,
            )
        )
    return prs, direct


class Linear:
    def __init__(self, api_key: str) -> None:
        self.api_key = api_key
        self._issues: dict[str, dict | None] = {}

    def _gql(self, query: str, variables: dict) -> dict:
        req = urllib.request.Request(
            LINEAR_URL,
            data=json.dumps({"query": query, "variables": variables}).encode(),
            headers={"Authorization": self.api_key, "Content-Type": "application/json"},
        )
        with urllib.request.urlopen(req, timeout=20) as resp:
            payload = json.loads(resp.read())
        if payload.get("errors"):
            raise RuntimeError(payload["errors"])
        return payload["data"]

    def issue(self, ident: str) -> dict | None:
        if ident not in self._issues:
            try:
                self._issues[ident] = self._gql(
                    "query($id: String!) { issue(id: $id) { id identifier "
                    "labels { nodes { name } } } }",
                    {"id": ident},
                )["issue"]
            except Exception as exc:  # noqa: BLE001 - Linear must never fail the run
                warn(f"Linear lookup failed for {ident}: {exc}")
                self._issues[ident] = None
        return self._issues[ident]

    def comment_bodies(self, issue: dict) -> list[str]:
        """Every comment body on the issue, following pagination."""
        if "comment_bodies" not in issue:
            bodies: list[str] = []
            cursor = None
            while True:
                page = self._gql(
                    "query($id: String!, $after: String) { issue(id: $id) { "
                    "comments(first: 100, after: $after) { nodes { body } "
                    "pageInfo { hasNextPage endCursor } } } }",
                    {"id": issue["id"], "after": cursor},
                )["issue"]["comments"]
                bodies += [n.get("body") or "" for n in page["nodes"]]
                if not page["pageInfo"]["hasNextPage"]:
                    break
                cursor = page["pageInfo"]["endCursor"]
            issue["comment_bodies"] = bodies
        return issue["comment_bodies"]

    def risk(self, ident: str) -> str | None:
        issue = self.issue(ident)
        if not issue:
            return None
        names = {n["name"] for n in issue["labels"]["nodes"]}
        return next((r for r in RISK_LABELS if r in names), None)

    def comment_once(self, ident: str, body: str, marker: str) -> bool:
        issue = self.issue(ident)
        if not issue:
            return False
        try:
            if any(marker in b for b in self.comment_bodies(issue)):
                return False
        except Exception as exc:  # noqa: BLE001
            warn(f"Linear comment lookup failed for {ident}: {exc}")
            return False
        try:
            self._gql(
                "mutation($id: String!, $body: String!) { "
                "commentCreate(input: { issueId: $id, body: $body }) { success } }",
                {"id": issue["id"], "body": body},
            )
        except Exception as exc:  # noqa: BLE001
            warn(f"Linear comment failed for {ident}: {exc}")
            return False
        issue["comment_bodies"].append(body)
        return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--repo", default=os.environ.get("GITHUB_REPOSITORY", "widarecu/agentfx")
    )
    parser.add_argument(
        "--no-create", action="store_true", help="only refresh an open promote PR"
    )
    parser.add_argument(
        "--dry-run", action="store_true", help="print the body, change nothing"
    )
    args = parser.parse_args(argv)
    now = datetime.now(UTC)

    if not fleet_has_new_content():
        print(f"`{HEAD}` has no content `{BASE}` lacks; nothing to promote.")
        return 0

    open_prs = (
        _gh_json(
            "pr",
            "list",
            "--repo",
            args.repo,
            "--base",
            BASE,
            "--state",
            "open",
            "--limit",
            "1000",
            "--json",
            "number,url,title,body,headRefName,labels",
        )
        or []
    )
    existing, kind = select_open_promote(open_prs)
    if kind == "manual":
        print(
            f"::notice ::Hand-cut promote PR is open ({existing['url']}); not opening another."
        )
        stale = find_auto_promote(open_prs)
        if stale and not args.dry_run:
            res = _run(
                "gh",
                "pr",
                "close",
                stale["url"],
                "--comment",
                f"Superseded by frozen promote {existing['url']}. The promote "
                "workflow opens a fresh one once that is merged or closed.",
                check=False,
            )
            if res.returncode == 0:
                print(
                    f"Closed live promote PR {stale['url']} in favour of the frozen one."
                )
            else:
                warn(f"Could not close {stale['url']}: {res.stderr.strip()}")
        return 0
    if existing is None and args.no_create:
        print("No open promote PR and --no-create set; the push/schedule run opens it.")
        return 0

    prs, direct = collect(args.repo)
    linear = (
        Linear(os.environ["LINEAR_API_KEY"])
        if os.environ.get("LINEAR_API_KEY")
        else None
    )
    if linear is None:
        warn(
            "LINEAR_API_KEY not set: risk falls back to the `needs-wilson` label; no Linear comments."
        )
    for pr in prs:
        risks = [linear.risk(i) for i in afx_ids(pr.title)] if linear else []
        pr.risk = pick_risk(risks, pr.labels)

    head_sha = _run("git", "rev-parse", f"origin/{HEAD}").stdout.strip()
    section = render_section(prs, direct, repo=args.repo, head_sha=head_sha, now=now)
    body = merge_body(existing["body"] if existing else None, section)

    if args.dry_run:
        print(body)
        return 0

    with open("promote-body.md", "w", encoding="utf-8") as fh:
        fh.write(body)

    if existing:
        number, url = existing["number"], existing["url"]
        _run("gh", "pr", "edit", url, "--body-file", "promote-body.md")
        print(f"Refreshed promote PR: {url}")
    else:
        url = (
            _run(
                "gh",
                "pr",
                "create",
                "--repo",
                args.repo,
                "--base",
                BASE,
                "--head",
                HEAD,
                "--title",
                promote_title(now),
                "--body-file",
                "promote-body.md",
            )
            .stdout.strip()
            .splitlines()[-1]
        )
        number = int(url.rstrip("/").rsplit("/", 1)[-1])
        print(f"Opened promote PR: {url}")

    if not args.no_create:
        for label in (PROMOTE_LABEL, NEEDS_WILSON):
            res = _run("gh", "pr", "edit", url, "--add-label", label, check=False)
            if res.returncode != 0:
                warn(f"Could not add `{label}` to {url}: {res.stderr.strip()}")

    if linear:
        for pr in prs:
            for ident in afx_ids(pr.title):
                if linear.comment_once(
                    ident,
                    linear_comment(pr, promote_url=url, promote_number=number),
                    linear_marker(number),
                ):
                    print(f"Commented on {ident}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
